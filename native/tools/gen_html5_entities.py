#!/Library/Frameworks/Python.framework/Versions/3.14/bin/python3
"""Writes native/Sources/JarvisCore/PyCompat/HTML5Entities.swift from this Python's html module
(W1 part 1): html.entities.html5 and the two tables html.unescape reads, _invalid_charrefs and
_invalid_codepoints. PyHTML.unescape uses them; the w1_html golden suite proves the result.

    gen_html5_entities.py           write the file
    gen_html5_entities.py --check   exit 1 if the file differs from what would be written
"""
import html
import html.entities
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "Sources" / "JarvisCore" / "PyCompat" / "HTML5Entities.swift"


def render():
    lines = [
        "// Generated by native/tools/gen_html5_entities.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor}'s html module. Never edit by hand.",
        "// W1 part 1: the tables Python's html.unescape reads, for PyHTML.unescape.",
        "",
        "enum HTML5Entities {",
        "    /// html.entities.html5: one entry a line, the name, a tab, then its code points in hex.",
        '    static let table = """',
    ]
    for name in sorted(html.entities.html5):
        value = html.entities.html5[name]
        lines.append(f"        {name}\\t" + " ".join(f"{ord(c):X}" for c in value))
    lines.append('        """')
    lines.append("")
    lines.append("    /// html._invalid_charrefs: a numeric reference's replacement, by code point.")
    lines.append("    static let invalidCharrefs: [UInt32: UInt32] = [")
    for num, value in sorted(html._invalid_charrefs.items()):
        assert len(value) == 1
        lines.append(f"        0x{num:X}: 0x{ord(value):X},")
    lines.append("    ]")
    lines.append("")
    lines.append("    /// html._invalid_codepoints: numeric references that become nothing.")
    lines.append("    static let invalidCodepoints: Set<UInt32> = [")
    points = sorted(html._invalid_codepoints)
    for i in range(0, len(points), 8):
        lines.append("        " + " ".join(f"0x{p:X}," for p in points[i:i + 8]))
    lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render()
    if argv[1:] == ["--check"]:
        same = OUT.exists() and OUT.read_text() == text
        print("HTML5Entities.swift is " + ("current" if same else "STALE"))
        return 0 if same else 1
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(html.entities.html5)} entities)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
