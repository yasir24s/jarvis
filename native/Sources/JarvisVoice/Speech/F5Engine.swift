import Foundation
import Synchronization

/// One running jarvis-voice helper, as F5Engine sees it. `VoiceHelperProcess` is the real one;
/// tests use a fake, so the default `swift test` never starts the helper or loads a model.
public protocol VoiceHelperConnection: Sendable {
    /// The helper's stdout, one element per line without its newline. Finishes when it exits.
    var lines: AsyncStream<String> { get }
    /// Writes one request line; the newline is added here.
    func send(_ line: String) throws
    /// Closes the helper's stdin (it exits on EOF) and waits up to `grace`, then kills it.
    func close(grace: Duration) async
    /// Ends the helper now.
    func terminate()
}

/// Starts helpers. The helper writes its PCM files into `outDirectory` (its `--out-dir`).
public protocol VoiceHelperLauncher: Sendable {
    var outDirectory: URL { get }
    /// Whether the helper binary and the voice assets are on disk. F5 is unavailable without them.
    func isInstalled() -> Bool
    func launch() throws -> any VoiceHelperConnection
    /// The frames F5 would generate for `text`, as sent to the helper, reference included; nil
    /// when that cannot be told.
    func frames(forSpokenText text: String) -> Int?
}

extension VoiceHelperLauncher {
    public func frames(forSpokenText text: String) -> Int? { nil }
}

/// The F5-TTS voice clone (D-54), generated by the jarvis-voice helper process. The helper is
/// started on the first request and talks JSON lines (VoiceHelper/Sources/jarvis-voice); each
/// reply names a raw float32 file, which is read and deleted here.
///
/// Failures: a request that fails (an error reply, a crash, no reply in `timeout`, a file that
/// cannot be read) throws, and the queue speaks that part with `say`. After a crash or a timeout
/// the next request starts a fresh helper. Two failures in a row rest F5 for `restPeriod`: it
/// reports unavailable and every request throws `.disabled` until then.
public actor F5Engine: SpeechEngine {
    public nonisolated let id = EngineID.f5
    public static let sampleRate = 24_000.0
    public static let defaultTimeout = Duration.seconds(120)
    public static let restPeriod = Duration.seconds(600)
    /// The most frames F5 generates, the reference's included (the helper's `Voice.maxFrames`).
    public static let maxFrames = 4096

    private let launcher: any VoiceHelperLauncher
    private let timeout: Duration
    private let now: @Sendable () -> ContinuousClock.Instant
    /// Read without the actor: whether F5 is resting, and the helper's last footprint.
    private let shared = Mutex(Shared())

    private struct Shared {
        var restingUntil: ContinuousClock.Instant?
        var lastFootprintMB: Int?
    }

    private var connection: (any VoiceHelperConnection)?
    /// Numbers each helper started, so a late line or exit from an old one is ignored.
    private var connectionNumber = 0
    private var waiting: [String: CheckedContinuation<HelperReply, any Error>] = [:]
    private var timers: [String: Task<Void, Never>] = [:]
    private var failuresInARow = 0
    /// The helper that has loaded the model, or been asked to (`warm`, or a reply).
    private var loadedConnection: Int?

    public init(launcher: any VoiceHelperLauncher, timeout: Duration = F5Engine.defaultTimeout,
                now: @escaping @Sendable () -> ContinuousClock.Instant = { ContinuousClock.now }) {
        self.launcher = launcher
        self.timeout = timeout
        self.now = now
    }

    /// False when the helper or its assets are missing, or while F5 rests after two failures in
    /// a row. The app reports "say" as its voice then (`SpeakContext.ttsBackend`).
    public nonisolated var isAvailable: Bool {
        guard launcher.isInstalled() else { return false }
        guard let until = shared.withLock({ $0.restingUntil }) else { return true }
        return now() >= until
    }

    /// The helper's physical footprint in its last reply, in MB.
    public nonisolated var lastFootprintMB: Int? {
        shared.withLock { $0.lastFootprintMB }
    }

    /// Whether a helper is running.
    var isConnected: Bool { connection != nil }

    /// V1 part 2: why `text` cannot be generated in one go, or nil. It cannot when F5 would need
    /// more than `maxFrames` frames for it, as the helper is sent it (digits in words), with the
    /// reference and speed the helper would use. nil also when that cannot be told: the helper
    /// then refuses it itself, and the queue falls back as for any failure.
    public nonisolated func tooLong(_ text: String) -> String? {
        guard let frames = launcher.frames(forSpokenText: SpeechNormaliser.spoken(text)),
              frames > Self.maxFrames else { return nil }
        return "needs \(frames) frames, F5 stops at \(Self.maxFrames)"
    }

    public func synthesize(_ sentence: String, context: SynthesisContext) -> AsyncThrowingStream<PCMChunk, any Error> {
        AsyncThrowingStream { continuation in
            let task = Task {
                do {
                    let samples = try await self.generate(sentence)
                    continuation.yield(PCMChunk(samples: samples, sampleRate: Self.sampleRate))
                    continuation.finish()
                } catch {
                    continuation.finish(throwing: error)
                }
            }
            continuation.onTermination = { _ in task.cancel() }
        }
    }

    /// V1 part 5: starts the helper, if none is running, and has it load the model now
    /// (`{"cmd": "load"}`), so the reply after the message being typed waits for neither. Nothing
    /// when F5 is unavailable or this helper has already loaded it or been asked to. A helper
    /// that cannot start is not counted as a failure here: the request that follows meets it.
    public func warm() async {
        guard isAvailable else { return }
        if connection != nil, loadedConnection == connectionNumber { return }
        guard let helper = try? connect() else { return }
        loadedConnection = connectionNumber
        try? helper.send(#"{"cmd":"load"}"#)
    }

    /// Closes the helper's stdin and waits up to 2 s for it to exit (idle, or quit).
    public func release() async {
        guard let connection else { return }
        self.connection = nil
        connectionNumber += 1   // its exit is not a crash
        resolveAll(throwing: CancellationError())
        await connection.close(grace: .seconds(2))
    }

    // MARK: - Requests

    /// One request: text in, 24 kHz mono samples out. F5 is given digits spelled out.
    func generate(_ text: String) async throws -> [Float] {
        if let until = shared.withLock({ $0.restingUntil }) {
            guard now() >= until else {
                throw SpeechEngineError(.disabled, "F5 is resting after two failures in a row")
            }
            shared.withLock { $0.restingUntil = nil }
        }
        guard launcher.isInstalled() else {
            throw SpeechEngineError(.disabled, "the voice helper or its assets are not installed")
        }
        let helper: any VoiceHelperConnection
        do {
            helper = try connect()
        } catch {
            failed()
            throw SpeechEngineError(.error, "cannot start the voice helper: \(error)")
        }
        let id = UUID().uuidString
        let line = try Self.requestLine(id: id, text: SpeechNormaliser.spoken(text))
        let number = connectionNumber
        let reply = try await withTaskCancellationHandler {
            try await withCheckedThrowingContinuation { (continuation: CheckedContinuation<HelperReply, any Error>) in
                do {
                    try helper.send(line)
                } catch {
                    failed()
                    continuation.resume(throwing: SpeechEngineError(.error, "cannot write to the voice helper: \(error)"))
                    return
                }
                waiting[id] = continuation
                let timeout = self.timeout
                timers[id] = Task { [weak self] in
                    try? await Task.sleep(for: timeout)
                    guard !Task.isCancelled else { return }
                    await self?.timedOut(id, connection: number)
                }
            }
        } onCancel: {
            Task { await self.abandon(id) }
        }
        guard reply.ok, let path = reply.path else {
            failed()
            throw SpeechEngineError(.error, reply.error ?? "the voice helper replied without audio")
        }
        let samples: [Float]
        do {
            samples = try readPCM(path, expected: reply.samples)
        } catch {
            failed()
            throw SpeechEngineError(.error, "cannot read the voice helper's audio: \(error)")
        }
        failuresInARow = 0
        if number == connectionNumber { loadedConnection = number }
        return samples
    }

    static func requestLine(id: String, text: String) throws -> String {
        let data = try JSONSerialization.data(withJSONObject: ["id": id, "text": text], options: [.sortedKeys])
        return String(decoding: data, as: UTF8.self)
    }

    private func connect() throws -> any VoiceHelperConnection {
        if let connection { return connection }
        let helper = try launcher.launch()
        connectionNumber += 1
        let number = connectionNumber
        connection = helper
        Task { [weak self] in
            for await line in helper.lines {
                await self?.received(line, connection: number)
            }
            await self?.exited(connection: number)
        }
        return helper
    }

    private func received(_ line: String, connection number: Int) {
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        guard let reply = try? decoder.decode(HelperReply.self, from: Data(line.utf8)) else { return }
        if let mb = reply.footprintMb {
            shared.withLock { $0.lastFootprintMB = mb }
        }
        guard let id = reply.id else { return }
        if let continuation = waiting.removeValue(forKey: id) {
            timers.removeValue(forKey: id)?.cancel()
            continuation.resume(returning: reply)
        } else if reply.ok, let path = reply.path, isOurs(path) {
            // A cancelled request's audio: nobody plays it.
            try? FileManager.default.removeItem(atPath: path)
        }
    }

    private func exited(connection number: Int) {
        guard number == connectionNumber else { return }
        connection = nil
        // Idle exit or a close: nothing was asked of it, so it is not a failure.
        guard !waiting.isEmpty else { return }
        resolveAll(throwing: SpeechEngineError(.error, "the voice helper stopped mid-request"))
        failed()
    }

    private func timedOut(_ id: String, connection number: Int) {
        guard waiting[id] != nil else { return }
        // No answer in time: the helper is stuck or starved. A fresh one starts next time.
        if number == connectionNumber, let connection {
            self.connection = nil
            connectionNumber += 1
            connection.terminate()
        }
        resolveAll(throwing: SpeechEngineError(.timeout, "no reply from the voice helper in \(timeout)"))
        failed()
    }

    private func abandon(_ id: String) {
        guard let continuation = waiting.removeValue(forKey: id) else { return }
        timers.removeValue(forKey: id)?.cancel()
        continuation.resume(throwing: CancellationError())
    }

    private func resolveAll(throwing error: any Error) {
        let pending = waiting
        waiting.removeAll()
        for (_, timer) in timers { timer.cancel() }
        timers.removeAll()
        for (_, continuation) in pending { continuation.resume(throwing: error) }
    }

    private func failed() {
        failuresInARow += 1
        guard failuresInARow >= 2 else { return }
        failuresInARow = 0
        let until = now().advanced(by: Self.restPeriod)
        shared.withLock { $0.restingUntil = until }
        // While F5 rests, its memory goes back to the system.
        if let connection {
            self.connection = nil
            connectionNumber += 1
            Task { await connection.close(grace: .seconds(2)) }
        }
    }

    // MARK: - Files

    private func isOurs(_ path: String) -> Bool {
        let url = URL(fileURLWithPath: path)
        return url.lastPathComponent.hasSuffix(".f32")
            && url.deletingLastPathComponent().standardizedFileURL.path
                == launcher.outDirectory.standardizedFileURL.path
    }

    /// Reads the helper's raw float32 little-endian file and deletes it.
    private func readPCM(_ path: String, expected: Int?) throws -> [Float] {
        guard isOurs(path) else {
            throw SpeechEngineError(.error, "the helper named a file outside its folder")
        }
        defer { try? FileManager.default.removeItem(atPath: path) }
        let data = try Data(contentsOf: URL(fileURLWithPath: path))
        guard data.count % MemoryLayout<Float>.size == 0 else {
            throw SpeechEngineError(.error, "\(data.count) bytes is not whole float32 samples")
        }
        var samples = [Float](repeating: 0, count: data.count / MemoryLayout<Float>.size)
        _ = samples.withUnsafeMutableBytes { data.copyBytes(to: $0) }   // Apple silicon is little-endian
        if let expected, expected != samples.count {
            throw SpeechEngineError(.error, "the file holds \(samples.count) samples, the reply said \(expected)")
        }
        return samples
    }
}

/// One line of the helper's stdout.
struct HelperReply: Decodable, Sendable {
    let id: String?
    let ok: Bool
    let path: String?
    let samples: Int?
    let rate: Int?
    let genMs: Int?
    let footprintMb: Int?
    let error: String?
}
